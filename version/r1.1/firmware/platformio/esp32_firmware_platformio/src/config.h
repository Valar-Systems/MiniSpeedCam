// --- GitHub auto-update (firmware now self-updates from GitHub Releases) ------
// Firmware updates no longer go through the manual Bubble "firmware_check" +
// web-UI buttons. Each device polls this PUBLIC repo's Releases for the latest
// tag, reads a manifest.json release asset for the per-MCU versions + .bin URLs
// + MD5s, and auto-applies any STRICTLY NEWER image while idle (see ota.h). The
// repo is public, so no token is embedded. Owner/repo are build-flag overridable
// so a fork can point the fleet at its own releases.
#ifndef GITHUB_OWNER
#define GITHUB_OWNER "Valar-Systems"
#endif
#ifndef GITHUB_REPO
#define GITHUB_REPO "MiniSpeedCam"
#endif

// Cadence. The unauthenticated GitHub API allows 60 requests/hour per IP; a
// multi-hour cadence stays far under that even for several units behind one NAT.
// The first check waits OTA_BOOT_CHECK_DELAY_MS after boot so it never competes
// with start-up / the first WiFi association.
#ifndef OTA_CHECK_INTERVAL_MS
#define OTA_CHECK_INTERVAL_MS (6UL * 60UL * 60UL * 1000UL)  // 6 hours
#endif
#ifndef OTA_BOOT_CHECK_DELAY_MS
#define OTA_BOOT_CHECK_DELAY_MS (2UL * 60UL * 1000UL)       // 2 minutes
#endif

// Health-check window for a freshly-applied ESP image. After applying, the new
// image must reach the cloud once within this window AND within OTA_HEALTH_MAX_BOOTS
// reboots, or the watchdog reverts to the previous slot (see otaHealthService()).
#ifndef OTA_HEALTH_TIMEOUT_MS
#define OTA_HEALTH_TIMEOUT_MS (5UL * 60UL * 1000UL)         // 5 minutes
#endif
#ifndef OTA_HEALTH_MAX_BOOTS
#define OTA_HEALTH_MAX_BOOTS 3                               // reboots before giving up + reverting
#endif

