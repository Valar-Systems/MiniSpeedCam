// --- Bootstrap bearer token (transport auth only) ---------------------------
// Authorizes the register_device / capture transport. It is NOT a user-data
// key: on its own it can only register a device or post a capture for an
// already-claimed device -- it cannot read or write a user's data. Because the
// previous shared key leaked into this repo's git history, the token is now
// REQUIRED at build time and intentionally has no in-source default:
//   build_flags = '-DAPI_BEARER_TOKEN="<rotated-bootstrap-token>"'
// The build fails loudly below if it is missing, so a unit can never ship with
// a stale/placeholder token baked in.
#ifndef API_BEARER_TOKEN
#error "API_BEARER_TOKEN is not defined. Pass it via a PlatformIO build flag, e.g. build_flags = '-DAPI_BEARER_TOKEN=\"<rotated-bootstrap-token>\"'. It must never be committed in source."
#endif
// Catch an EMPTY token too: an unset '${sysenv.MSC_BOOTSTRAP_TOKEN}' expands to
// "", which the #ifndef above cannot see (the macro is still "defined"). A bare
// "" has sizeof 1 (just the NUL), so this fails the build if no token was set.
static_assert(sizeof(API_BEARER_TOKEN) > 1,
              "API_BEARER_TOKEN is empty -- set MSC_BOOTSTRAP_TOKEN before building (it must not be committed in source).");

